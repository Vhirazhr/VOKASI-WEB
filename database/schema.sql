-- VOKASI standalone PostgreSQL bootstrap schema.
-- Derived from current VOKASI schema metadata; NO application data is included.
-- Apply ONLY to a new, empty PostgreSQL database owned by the VOKASI migration user.
-- This is the data/auth foundation. Application cutover is not complete until all UI
-- data calls and exam/admin operations have been moved to the native API.
BEGIN;

CREATE SCHEMA auth;
CREATE SCHEMA storage;
CREATE SCHEMA vokasi_private;

CREATE TABLE public.schema_migrations (
  version text PRIMARY KEY,
  applied_at timestamptz NOT NULL DEFAULT now()
);

-- Native identities replace hosted Auth. Preserve UUIDs during data import to keep references stable.
CREATE TABLE public.app_users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  username text NOT NULL,
  email text,
  email_verified_at timestamptz,
  display_name text NOT NULL DEFAULT '',
  password_hash text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz,
  CONSTRAINT app_users_username_length CHECK (length(btrim(username)) BETWEEN 2 AND 254),
  CONSTRAINT app_users_password_hash_nonempty CHECK (length(password_hash) > 0)
);
CREATE UNIQUE INDEX app_users_username_unique_ci ON public.app_users (lower(btrim(username)));
CREATE UNIQUE INDEX app_users_email_unique_ci ON public.app_users (lower(btrim(email))) WHERE email IS NOT NULL AND btrim(email) <> '';

-- Minimal compatibility surface for existing SQL business functions; this is not hosted Auth.
CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
SET search_path TO 'pg_catalog'
AS $function$
  SELECT NULLIF(current_setting('app.user_id', true), '')::uuid;
$function$;

CREATE VIEW auth.users AS
SELECT
  id,
  email,
  created_at,
  last_login_at AS last_sign_in_at,
  email_verified_at AS email_confirmed_at,
  NULL::timestamptz AS deleted_at,
  NULL::timestamptz AS banned_until,
  NULL::timestamptz AS invited_at,
  is_active
FROM public.app_users;

-- File metadata only. Actual bytes live under a private STORAGE_ROOT on the app server.
CREATE TABLE storage.objects (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  bucket_id text NOT NULL CHECK (bucket_id IN ('vokasi-question-figures', 'vokasi-avatars')),
  name text NOT NULL CHECK (btrim(name) <> ''),
  owner_id uuid REFERENCES public.app_users(id) ON DELETE SET NULL,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  mimetype text NOT NULL,
  size_bytes bigint NOT NULL CHECK (size_bytes >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (bucket_id, name)
);
CREATE INDEX storage_objects_owner_idx ON storage.objects (owner_id, created_at DESC);
CREATE INDEX storage_objects_bucket_idx ON storage.objects (bucket_id, created_at DESC);

CREATE TABLE public.app_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.app_users(id) ON DELETE CASCADE,
  token_hash char(64) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz,
  ip_hash char(64),
  user_agent text
);
CREATE INDEX app_sessions_user_active_idx ON public.app_sessions (user_id, expires_at DESC) WHERE revoked_at IS NULL;
CREATE INDEX app_sessions_expiry_idx ON public.app_sessions (expires_at);

CREATE TABLE public.app_login_attempts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  identifier_hash char(64) NOT NULL,
  ip_hash char(64),
  succeeded boolean NOT NULL DEFAULT false,
  attempted_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX app_login_attempts_identifier_recent_idx ON public.app_login_attempts (identifier_hash, attempted_at DESC) WHERE succeeded = false;
CREATE INDEX app_login_attempts_ip_recent_idx ON public.app_login_attempts (ip_hash, attempted_at DESC) WHERE succeeded = false;
CREATE INDEX app_login_attempts_expiry_idx ON public.app_login_attempts (attempted_at);

